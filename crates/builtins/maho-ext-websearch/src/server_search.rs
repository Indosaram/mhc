#[cfg(test)]
mod tests {
    use super::*;
    use maho_ai::providers::faux::{FauxAssistantMessageOptions, faux_assistant_message};
    use serde_json::json;

    fn model() -> Model {
        serde_json::from_value(json!({"id":"test", "name":"Test", "api":"openai-responses", "provider":"openai", "baseUrl":"https://api.openai.com/v1", "reasoning":false, "input":["text"], "cost":{"input":0,"output":0,"cacheRead":0,"cacheWrite":0}, "contextWindow":1000, "maxTokens":100})).unwrap()
    }

    fn failure() -> AssistantMessage {
        let mut message = faux_assistant_message("", FauxAssistantMessageOptions::default());
        message.stop_reason = StopReason::Error;
        message.error_message = Some("HTTP 400 unsupported web_search_preview".into());
        message
    }

    #[test]
    fn structured_errors_accept_object_and_array_content() {
        for raw in [
            json!({"type":"web_search_call","status":"failed"}),
            json!({"type":"web_search_tool_result", "content":{"type":"web_search_tool_result_error"}}),
            json!({"type":"web_search_tool_result", "content":[{"type":"web_search_tool_result_error"}]}),
        ] {
            let mut message = faux_assistant_message("", FauxAssistantMessageOptions::default());
            message.content = vec![ContentBlock::ProviderNative(
                maho_ai::types::ProviderNativeContent {
                    subtype: raw["type"].as_str().unwrap().into(),
                    raw,
                },
            )];
            assert!(search_failed(&message));
            message.stop_reason = StopReason::Aborted;
            assert!(!search_failed(&message));
        }
    }

    #[test]
    fn unrelated_errors_and_generated_text_do_not_disable_search() {
        for error in [
            "401 web_search_preview",
            "quota exceeded web_search",
            "billing web_search",
            "connection reset",
        ] {
            let mut message = failure();
            message.error_message = Some(error.into());
            assert!(!search_failed(&message));
        }
        assert!(!search_failed(&faux_assistant_message(
            "web_search_tool_result_error",
            FauxAssistantMessageOptions::default()
        )));
        assert!(search_failed(&failure()));
    }

    #[test]
    fn failure_is_endpoint_scoped_and_continues_only_once() {
        let model = model();
        let mut other = model.clone();
        other.base_url = "https://other.example/v1".into();
        let mut state = ServerSearchState::default();
        assert!(state.record_failure(&model, &failure()));
        assert!(state.failed(Some(&model)));
        assert!(!state.failed(Some(&other)));
        assert!(state.take_continuation(Some(&model)));
        assert!(!state.take_continuation(Some(&model)));
        assert!(!state.record_failure(&model, &failure()));
    }

    #[test]
    fn cancellation_and_core_retry_suppress_continuation() {
        for event in [
            ExtensionEvent::SessionAbort,
            ExtensionEvent::AgentEnd {
                messages: vec![],
                aborted: None,
                will_retry: Some(true),
                abort_source: None,
            },
            ExtensionEvent::AgentEnd {
                messages: vec![],
                aborted: Some(true),
                will_retry: None,
                abort_source: Some(maho_ext_api::AbortSource::User),
            },
        ] {
            let model = model();
            let mut state = ServerSearchState::default();
            state.record_failure(&model, &failure());
            state.end(&event);
            assert!(!state.take_continuation(Some(&model)));
            assert!(state.failed(Some(&model)));
        }
    }

    #[test]
    fn completed_answer_and_model_switch_do_not_duplicate_turn() {
        let model = model();
        let mut state = ServerSearchState::default();
        state.record_failure(
            &model,
            &faux_assistant_message("completed", FauxAssistantMessageOptions::default()),
        );
        assert!(!state.take_continuation(Some(&model)));
        let mut state = ServerSearchState::default();
        state.record_failure(&model, &failure());
        state.new_turn();
        assert!(!state.take_continuation(Some(&model)));
        assert!(state.failed(Some(&model)));
    }

    #[test]
    fn later_completed_answer_cancels_pending_recovery() {
        let model = model();
        let mut state = ServerSearchState::default();
        state.record_failure(&model, &failure());
        let mut answer =
            faux_assistant_message("completed", FauxAssistantMessageOptions::default());
        answer.api = model.api.clone();
        answer.provider = model.provider.clone();
        answer.model = model.id.clone();
        state.completed(&answer);
        assert!(!state.take_continuation(Some(&model)));
    }
}
