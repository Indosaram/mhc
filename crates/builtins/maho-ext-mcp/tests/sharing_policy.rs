#[test]
fn shared_identity_uses_pinned_locale_key_order() {
    let config = McpServerConfig {
        transport: Some(Transport::Stdio),
        command: Some("fixture".into()),
        args: Some(vec![]),
        cwd: Some("/cwd".into()),
        env: Some(BTreeMap::from([
            ("Z".into(), "1".into()),
            ("z".into(), "2".into()),
            ("a".into(), "3".into()),
            ("A".into(), "4".into()),
            ("é".into(), "5".into()),
            ("e".into(), "6".into()),
        ])),
        ..Default::default()
    };
    // Generated by pinned sharing-policy.ts sharedMcpKey with this identity.
    assert_eq!(
        shared_mcp_key(
            "fx",
            &config,
            Some(&BTreeMap::new()),
            None,
            "/agent",
            "/cwd"
        ),
        "043e6fda079fa6a6e83e12ad7323deaebb4dabf05801d7b61a14a12789cf1887"
    );
}
#[test]
fn identity_tracks_credentials_and_agent_directory_not_owner_policies() {
    let config=normalize_server(serde_json::from_value(json!({"type":"http","url":"http://127.0.0.1/mcp","auth":"bearer","bearerTokenEnv":"QA_TOKEN"})).unwrap());
    let env = BTreeMap::from([("QA_TOKEN".into(), "synthetic-A".into())]);
    let key = shared_mcp_key("fx", &config, Some(&env), None, "/agent-A", "/cwd");
    let mut policy = config.clone();
    policy.idle_timeout_min = Some(5.0);
    policy.lifecycle = Some(Lifecycle::KeepAlive);
    policy.exposure = Some(Exposure::Search);
    assert_eq!(
        shared_mcp_key("fx", &policy, Some(&env), None, "/agent-A", "/cwd"),
        key
    );
    assert_ne!(
        shared_mcp_key("fx", &config, Some(&env), None, "/agent-B", "/cwd"),
        key
    );
    let different = BTreeMap::from([("QA_TOKEN".into(), "synthetic-B".into())]);
    assert_ne!(
        shared_mcp_key("fx", &config, Some(&different), None, "/agent-A", "/cwd"),
        key
    );
}
#[test]
fn identity_keys_the_credential_identity() {
    let config = McpServerConfig {
        transport: Some(Transport::Stdio),
        command: Some("fixture".into()),
        args: Some(vec![]),
        cwd: Some("/cwd".into()),
        env: Some(BTreeMap::from([
            ("Z".into(), "1".into()),
            ("z".into(), "2".into()),
            ("a".into(), "3".into()),
            ("A".into(), "4".into()),
            ("é".into(), "5".into()),
            ("e".into(), "6".into()),
        ])),
        ..Default::default()
    };
    // Generated by sharing-policy.ts sharedMcpKey (v2026.10.27-2) with credentialIdentity "none".
    let none = shared_mcp_key(
        "fx",
        &config,
        Some(&BTreeMap::new()),
        Some("none"),
        "/agent",
        "/cwd",
    );
    assert_eq!(
        none,
        "576aa22c3430e3e2e7a7e4b7fdc0764b9bcb9ec6c4d81ad937b926d339213631"
    );
    assert_ne!(
        shared_mcp_key(
            "fx",
            &config,
            Some(&BTreeMap::new()),
            Some("other"),
            "/agent",
            "/cwd"
        ),
        none
    );
}
#[tokio::test]
async fn identity_keys_a_project_skill_servers_authority_digests() {
    let root = tempfile::tempdir().expect("temporary project root");
    let skill = root.path().join("SKILL.md");
    std::fs::write(
        &skill,
        "---\nname: fixture\nmcp:\n  probe:\n    command: server\n---\n",
    )
    .expect("write skill");
    let declarations =
        maho_ext_mcp::skills::parse_skill_mcp_declarations(&[maho_ext_mcp::skills::SkillLike {
            name: "fixture".into(),
            file_path: skill,
            base_dir: root.path().into(),
            scope: Some("project".into()),
            ..Default::default()
        }]);
    let server = maho_ext_mcp::project_skill_policy::prepare_project_skill_server(
        "probe",
        &declarations.servers["probe"],
        root.path(),
        root.path(),
        true,
        &BTreeMap::new(),
        None,
    )
    .await
    .expect("project skill server");
    let governed = server.config.expect("resolved config");
    let authority = maho_ext_mcp::project_skill_policy::get_project_mcp_authority(&governed)
        .expect("project authority");
    let mut plain = governed.clone();
    plain.project_authority = None;
    let env = BTreeMap::new();
    let key = shared_mcp_key(
        "probe",
        &governed,
        Some(&env),
        Some("none"),
        "/agent",
        "/cwd",
    );
    // sharing-policy.ts: a governed declaration never pools with an ungoverned one of the same transport.
    assert_ne!(
        key,
        shared_mcp_key("probe", &plain, Some(&env), Some("none"), "/agent", "/cwd")
    );
    let identity = serde_json::json!({
        "agentDir":"/agent","args":plain.args,"auth":plain.auth,"bearer":null,"command":plain.command,"connectTimeoutMs":plain.connect_timeout_ms,
        "credentialIdentity":"none","cwd":plain.cwd.as_deref().unwrap_or("/cwd"),"declarationDigest":authority.identity,"env":plain.env.clone().unwrap_or_default(),
        "headers":plain.headers,"logLevel":plain.log_level,"name":"probe","oauth":plain.oauth,"policyDigest":authority.policy_digest,
        "skillAuthorityDigest":authority.provenance_digest,"type":plain.transport,"url":null,
    });
    // Every key here is ASCII lowercase-first, so plain byte order equals localeCompare order.
    let stable = |value: &serde_json::Value| -> String {
        fn walk(value: &serde_json::Value) -> String {
            match value {
                serde_json::Value::Object(map) => {
                    let mut keys = map.keys().collect::<Vec<_>>();
                    keys.sort_by_key(|key| key.to_lowercase());
                    format!(
                        "{{{}}}",
                        keys.into_iter()
                            .map(|key| format!("{}:{}", serde_json::json!(key), walk(&map[key])))
                            .collect::<Vec<_>>()
                            .join(",")
                    )
                }
                serde_json::Value::Array(items) => {
                    format!("[{}]", items.iter().map(walk).collect::<Vec<_>>().join(","))
                }
                _ => value.to_string(),
            }
        }
        walk(value)
    };
    use sha2::Digest;
    assert_eq!(
        key,
        format!("{:x}", sha2::Sha256::digest(stable(&identity)))
    );
}
