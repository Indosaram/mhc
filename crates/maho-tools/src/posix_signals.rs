pub fn posix_signal_number(os: &str, signal: &str) -> Option<i32> {
    if os == "linux" || os == "android" {
        return match signal {
            "SIGHUP" => Some(1),
            "SIGINT" => Some(2),
            "SIGQUIT" => Some(3),
            "SIGILL" => Some(4),
            "SIGTRAP" => Some(5),
            "SIGABRT" | "SIGIOT" => Some(6),
            "SIGBUS" => Some(7),
            "SIGFPE" => Some(8),
            "SIGKILL" => Some(9),
            "SIGUSR1" => Some(10),
            "SIGSEGV" => Some(11),
            "SIGUSR2" => Some(12),
            "SIGPIPE" => Some(13),
            "SIGALRM" => Some(14),
            "SIGTERM" => Some(15),
            "SIGSTKFLT" => Some(16),
            "SIGCHLD" => Some(17),
            "SIGCONT" => Some(18),
            "SIGSTOP" => Some(19),
            "SIGTSTP" => Some(20),
            "SIGTTIN" => Some(21),
            "SIGTTOU" => Some(22),
            "SIGURG" => Some(23),
            "SIGXCPU" => Some(24),
            "SIGXFSZ" => Some(25),
            "SIGVTALRM" => Some(26),
            "SIGPROF" => Some(27),
            "SIGWINCH" => Some(28),
            "SIGIO" | "SIGPOLL" => Some(29),
            "SIGPWR" => Some(30),
            "SIGSYS" => Some(31),
            _ => None,
        };
    }

    if matches!(
        os,
        "darwin" | "macos" | "freebsd" | "openbsd" | "netbsd" | "dragonfly"
    ) {
        return match signal {
            "SIGHUP" => Some(1),
            "SIGINT" => Some(2),
            "SIGQUIT" => Some(3),
            "SIGILL" => Some(4),
            "SIGTRAP" => Some(5),
            "SIGABRT" | "SIGIOT" => Some(6),
            "SIGEMT" => Some(7),
            "SIGFPE" => Some(8),
            "SIGKILL" => Some(9),
            "SIGBUS" => Some(10),
            "SIGSEGV" => Some(11),
            "SIGSYS" => Some(12),
            "SIGPIPE" => Some(13),
            "SIGALRM" => Some(14),
            "SIGTERM" => Some(15),
            "SIGURG" => Some(16),
            "SIGSTOP" => Some(17),
            "SIGTSTP" => Some(18),
            "SIGCONT" => Some(19),
            "SIGCHLD" => Some(20),
            "SIGTTIN" => Some(21),
            "SIGTTOU" => Some(22),
            "SIGIO" => Some(23),
            "SIGXCPU" => Some(24),
            "SIGXFSZ" => Some(25),
            "SIGVTALRM" => Some(26),
            "SIGPROF" => Some(27),
            "SIGWINCH" => Some(28),
            "SIGINFO" => Some(29),
            "SIGUSR1" => Some(30),
            "SIGUSR2" => Some(31),
            _ => None,
        };
    }

    if os == "win32" || os == "windows" {
        return match signal {
            "SIGHUP" => Some(1),
            "SIGINT" => Some(2),
            "SIGQUIT" => Some(3),
            "SIGILL" => Some(4),
            "SIGTRAP" => Some(5),
            "SIGABRT" => Some(22),
            "SIGFPE" => Some(8),
            "SIGKILL" => Some(9),
            "SIGSEGV" => Some(11),
            "SIGPIPE" => Some(13),
            "SIGALRM" => Some(14),
            "SIGTERM" => Some(15),
            "SIGBREAK" => Some(21),
            "SIGWINCH" => Some(28),
            _ => None,
        };
    }

    match signal {
        "SIGHUP" => Some(1),
        "SIGINT" => Some(2),
        "SIGQUIT" => Some(3),
        "SIGILL" => Some(4),
        "SIGTRAP" => Some(5),
        "SIGABRT" => Some(6),
        "SIGFPE" => Some(8),
        "SIGKILL" => Some(9),
        "SIGSEGV" => Some(11),
        "SIGPIPE" => Some(13),
        "SIGALRM" => Some(14),
        "SIGTERM" => Some(15),
        _ => None,
    }
}

