pub fn symbol_kind_name(kind: u32) -> Option<&'static str> {
    const NAMES: [&str; 26] = [
        "File",
        "Module",
        "Namespace",
        "Package",
        "Class",
        "Method",
        "Property",
        "Field",
        "Constructor",
        "Enum",
        "Interface",
        "Function",
        "Variable",
        "Constant",
        "String",
        "Number",
        "Boolean",
        "Array",
        "Object",
        "Key",
        "Null",
        "EnumMember",
        "Struct",
        "Event",
        "Operator",
        "TypeParameter",
    ];
    let index = usize::try_from(kind).ok()?.checked_sub(1)?;
    NAMES.get(index).copied()
}

pub fn severity_name(severity: u32) -> Option<&'static str> {
    match severity {
        1 => Some("error"),
        2 => Some("warning"),
        3 => Some("information"),
        4 => Some("hint"),
        _ => None,
    }
}

