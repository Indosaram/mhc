pub fn is_known_extension(ext: &str) -> bool {
    EXT_TO_LANG.iter().any(|(key, _)| *key == ext)
}

/// TS `getLanguageId`.
pub fn get_language_id(ext: &str) -> &'static str {
    EXT_TO_LANG
        .iter()
        .find(|(key, _)| *key == ext)
        .map_or("plaintext", |(_, lang)| lang)
}
