#!/usr/bin/env bun
// Generates crates/maho-tui/src/unicode_tables.rs from the pinned senpi toolchain so the Rust width
// code classifies code points exactly like senpi's utils.ts does under bun:
//   - JS regex Unicode properties (Default_Ignorable_Code_Point, Control, Mark, Surrogate, Format,
//     Spacing_Mark, CJK Script_Extensions, \s) evaluated by bun itself,
//   - eastAsianWidth() from senpi's get-east-asian-width 1.7.0,
//   - the RGI emoji set: every sequence listed in the vendored Unicode 17.0.0 emoji data files,
//     cross-checked against bun's /^\p{RGI_Emoji}$/v.
//
//   bun crates/maho-tui/scripts/gen-unicode-tables.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { pinnedSenpiRoot } from "../../../tools/golden/pin.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const crateRoot = resolve(here, "..");
const senpi = pinnedSenpiRoot();
const eawPkg = join(senpi, "node_modules/get-east-asian-width");
const eawVersion = JSON.parse(readFileSync(join(eawPkg, "package.json"), "utf8")).version;
if (eawVersion !== "1.7.0") throw new Error(`get-east-asian-width ${eawVersion}, expected 1.7.0`);
const { eastAsianWidth } = await import(pathToFileURL(join(eawPkg, "index.js")).href);

const FLAGS = [
	["DI", /^\p{Default_Ignorable_Code_Point}$/v],
	["CC", /^\p{Control}$/v],
	["MARK", /^\p{Mark}$/v],
	["CS", /^\p{Surrogate}$/v],
	["CF", /^\p{Format}$/v],
	["MC", /^\p{Spacing_Mark}$/v],
	["CJK", /^[\p{Script_Extensions=Han}\p{Script_Extensions=Hiragana}\p{Script_Extensions=Katakana}\p{Script_Extensions=Hangul}\p{Script_Extensions=Bopomofo}]$/u],
	["WS", /^\s$/],
];

function charOf(cp) {
	// Lone surrogates are valid JS strings; String.fromCodePoint yields the single code unit.
	return String.fromCodePoint(cp);
}

const ranges = [];
let cur = null;
for (let cp = 0; cp <= 0x10ffff; cp++) {
	const ch = charOf(cp);
	let flags = 0;
	FLAGS.forEach(([, re], i) => {
		if (re.test(ch)) flags |= 1 << i;
	});
	if (eastAsianWidth(cp) === 2) flags |= 1 << FLAGS.length;
	if (cur && cur[2] === flags && cur[1] === cp - 1) cur[1] = cp;
	else {
		cur = [cp, cp, flags];
		ranges.push(cur);
	}
}
const nonZero = ranges.filter((r) => r[2] !== 0);

// RGI emoji from the vendored Unicode 17 data.
const dataDir = join(crateRoot, "data/unicode-17.0.0");
const rgi = new Set();
for (const file of ["emoji-sequences.txt", "emoji-zwj-sequences.txt"]) {
	for (const raw of readFileSync(join(dataDir, file), "utf8").split("\n")) {
		const line = raw.replace(/#.*/, "").trim();
		if (!line) continue;
		const field = line.split(";")[0].trim();
		if (field.includes("..")) {
			const [lo, hi] = field.split("..").map((h) => Number.parseInt(h, 16));
			for (let cp = lo; cp <= hi; cp++) rgi.add(String.fromCodePoint(cp));
		} else {
			rgi.add(String.fromCodePoint(...field.split(/\s+/).map((h) => Number.parseInt(h, 16))));
		}
	}
}
const rgiRegex = /^\p{RGI_Emoji}$/v;
const disagree = [...rgi].filter((s) => !rgiRegex.test(s));
if (disagree.length > 0) throw new Error(`bun rejects ${disagree.length} listed RGI sequences, e.g. ${JSON.stringify(disagree.slice(0, 3))}`);
const rgiList = [...rgi].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
// Rust sorts &str by UTF-8 bytes; JS by UTF-16 units. Sort by UTF-8 bytes for binary search.
rgiList.sort((a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b)));

const esc = (s) => [...s].map((c) => `\\u{${c.codePointAt(0).toString(16)}}`).join("");
let out = "";
out += "// @generated by crates/maho-tui/scripts/gen-unicode-tables.mjs - do not edit.\n";
out += `// Sources: bun ${Bun.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}) regex properties,\n`;
out += `// get-east-asian-width ${eawVersion} (senpi node_modules), Unicode 17.0.0 emoji-sequences/emoji-zwj-sequences.\n\n`;
FLAGS.forEach(([name], i) => {
	out += `pub(crate) const ${name}: u16 = 1 << ${i};\n`;
});
out += `pub(crate) const WIDE: u16 = 1 << ${FLAGS.length};\n\n`;
out += "/// Sorted, non-overlapping (first, last, flags) ranges; code points not listed have no flags.\n";
out += `pub(crate) static CODEPOINT_FLAGS: [(u32, u32, u16); ${nonZero.length}] = [\n`;
for (const [lo, hi, f] of nonZero) out += `    (0x${lo.toString(16)}, 0x${hi.toString(16)}, ${f}),\n`;
out += "];\n\n";
out += "/// Every RGI emoji sequence, sorted by UTF-8 bytes.\n";
out += `pub(crate) static RGI_EMOJI: [&str; ${rgiList.length}] = [\n`;
for (const s of rgiList) out += `    "${esc(s)}",\n`;
out += "];\n";
const target = join(crateRoot, "src/unicode_tables.rs");
writeFileSync(target, out);
console.log(`wrote ${target} (${nonZero.length} ranges, ${rgiList.length} RGI sequences)`);
