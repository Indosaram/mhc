import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const root = process.env.PI_RULES_SRC;
if (!root) throw new Error("PI_RULES_SRC is required");
const picomatch = createRequire(`${root}/package.json`)("picomatch");
const patterns = ["@(foo|bar).ts", "+(foo|bar).ts", "?(foo|bar).ts", "*(foo|bar).ts", "a@(b|c)d", "@(a|+(b|c))", "a(b|c)", "@(a|b", "{1..12}", "{1..9..2}", "{a..z}", "[abc", "a{b", "a{b,c", "a{b}", "a}b"];
const paths = ["foo.ts", "bar.ts", ".ts", "foobar.ts", "foofoo.ts", "xfoo.ts", "abd", "acd", "ad", "a", "b", "bb", "bc", "ab", "ac", "(a", "1", "2", "9", "12", "z", "[abc", "a{b", "a{b,c", "a{b}", "a}b"];
patterns.push("src/*(foo|bar).ts", "a?(b)c", "a+(b)c", "@(a|b){1..3}", "a(b", "a)b", "{z..a}");
paths.push("src/foo.ts", "src/.ts", "abc", "abbc", "a1", "b2", "a(b", "a)b");
patterns.push("+(a|aa)", "*(a|aa)");
paths.push("aa", "+(a|aa)", "*(a|aa)");
patterns.push("x/!(foo|bar)", "x/!(*.d).ts", "a!(b)c", "@(a|b){x,y}");
paths.push("x/foo", "x/bar", "x/baz", "x/foo/child", "x/a.d.ts", "x/a.ts", "ax", "by", "ac", "axc");
patterns.push("+(*(a)|*(b))", "+(*(a)|b)", "+(*(ab)|b)", "+(a|+(b|c))", "+(a|@(aa))");
paths.push("ba", "abab", "+(*(ab)|b)", "+(a|+(b|c))", "+(a|@(aa))");
patterns.push("@(a|b)[abc]", "@(a|b)[!x]", "@(a|b)[^x]", "@(a|b){x,{y,z}}");
paths.push("a[abc]", "a[!x]", "a!", "aa/", "a/", "ay", "az");
patterns.push('@(a|b)[[:digit:]]', '@(a|b)[[:alpha:]]', '@(a|b)"*"', '@(a|b)"?"');
paths.push("a0", "b9", "aZ", "a*", "b?", 'a"*"');
patterns.push('"*"', '@(a|b)[]', '@(a|b)[^]', '@(a|b)[z-a]', '@(a|b)[a-]');
paths.push("*", "a[]", "a[^]", "a[z-a]", "a-", "a[]/");
patterns.push('[]', '[^]', '[z-a]', '[!x]', '[abc]', '[[:digit:]]');
paths.push('[]', '[^]', '[z-a]', '!', '[abc]', '[]/');
patterns.push('*', '**', '**/a', 'a/*', 'a/**', 'a?', 'a{b,c}', 'a|b', 'a+b', 'a**b');
paths.push('', '.', '..', 'x/.', 'x/..', 'x/a', 'a/.', 'a/..', 'a/x', 'a/x/y', 'a/b', 'ab/', 'a/b/', 'a/');
patterns.push('a/**/b', 'a*/b', '{a,{b,c}}', 'a{b', 'a{b,c', 'a**/b', '*/a');
paths.push('ab', 'b', 'c', 'a/b', 'a/x/b', 'ax/b', 'a/x/../b', '/a', 'a{bmore');
patterns.push('./a', 'a/**/**/b', '@(a|b)?', 'a/**/', '@(a|b)|c', 'a|@(b|c)');
paths.push('a/x/', 'a/x/y/', './a', '');
patterns.push('@(a|b)+', '(ab)+', '(ab+)', '(?=a)a', '(?:a|b)', 'a{b,c}+', '[ab]+');
paths.push('aaa', 'abb', 'abab', 'acbc', '[ab][ab]');
patterns.push('@(a|b)[[:punct:]]', '@(a|b)[!x]', '@(a|b)[^x]', '@(a|b)[a-]', '@(a|b)[[]', '@(a|b)[a/b]');
paths.push('a!', 'a[', 'a]', 'a-', 'a/', 'a[!x]', 'a[a/b]', 'a^', 'a~');
patterns.push('@(a|b)[^[:digit:]]', '@(a|b)[]x]', '@(a|b)[^]x]', '@(a|b)[a&&b]', '@(a|b)[a~b]', 'a{1..3}');
paths.push('ax', 'a1', 'a2', 'a&', 'a[a&&b]', 'a[a~b]');
patterns.push('+(*(@(a))|b)', '*(*(@(a))*(b))', '+(*(@(ab))|c)', '+(@(a)|aa)', '+(*(a)|@(b))');
paths.push('aaaa', 'bbbb', 'ababa', 'cc');
patterns.push('@(a|b)[a||b]', '@(a|b)[a~~b]', '+( *(a) | b )', '+(a | aa)', '+("a"|b)');
paths.push('a|', 'a[a~~b]', 'a b', 'aa ');
patterns.push('?', '??', 'a?', 'a??');
paths.push('\ud83d\ude00', 'a\ud83d\ude00', '\n', 'a\n', '\r', '\u2028', '\u2029');
patterns.push('@(a|b)[\ud83d\ude00]', '@(a|b)\ud83d\ude00', '@(a|b)?\ud83d\ude00', '[\ud83d\ude00]*', '*\ud83d\ude00');
paths.push('\ud83d\ude00\ud83d\ude00', 'b\ud83d\ude00', 'a\n\ud83d\ude00');
patterns.push('@(a|b){x}', '@(a|b){1..3}', '@(a|b){x,y}', '@(a|b)[[:bogus:]]', '@(a|b)(?=c)c');
paths.push('a{x}', 'a3', 'ay', 'ac', 'a:]','as]', 'a[]');
for (const pattern of patterns) if (!paths.includes(pattern)) paths.push(pattern);
const cases = patterns.flatMap(pattern => { const matches = picomatch(pattern, { bash: true, dot: true }); return paths.map(path => ({ pattern, path, matched: matches(path) })); });
for (const pattern of ['!foo', '!!foo', '!@(a|b)', '!(a|b)', '![z-a]', '!"*"']) {
  const positive = picomatch('**', { bash: true, dot: true });
  const excluded = picomatch(pattern.slice(1), { bash: true, dot: true });
  for (const path of paths) cases.push({ pattern, path, matched: positive(path) && !excluded(path), exclusion: true });
}
const output = `${JSON.stringify(cases, null, 2)}\n`;
if (process.argv[2]) writeFileSync(process.argv[2], output);
else console.log(output);
