const home = mkdtempSync("/tmp/lane35-screen-");
const agentDir = join(home,"agent"); mkdirSync(agentDir);
for (const key of ["HOME","SENPI_CODING_AGENT_DIR","PI_CODING_AGENT_DIR","OMO_CODING_AGENT_DIR"]) process.env[key] = key === "HOME" ? home : agentDir;
Object.assign(process.env, { DO_NOT_TRACK:"1", OMO_DISABLE_POSTHOG:"1", SENPI_OFFLINE:"1", PI_OFFLINE:"1", COLORTERM:"truecolor", FORCE_COLOR:"3" });
const load = path => import(`${root}/${path}`);
const { setupFaux } = await import("./faux-common.mjs");
const faux = await setupFaux({ responses:[{ content:"hello",stopReason:"stop" }] },{omo:false});
const { SettingsManager } = await load("packages/coding-agent/src/core/settings-manager.ts");
const { SessionManager } = await load("packages/coding-agent/src/core/session-manager.ts");
const { createAgentSessionServices,createAgentSessionFromServices } = await load("packages/coding-agent/src/core/agent-session-services.ts");
const { AgentSessionRuntime } = await load("packages/coding-agent/src/core/agent-session-runtime.ts");
const { InteractiveMode } = await load("packages/coding-agent/src/modes/interactive/interactive-mode.ts");
const { createInteractiveTui } = await load("packages/coding-agent/src/modes/interactive/tui-renderer.ts");
const { VirtualTerminal } = await load("packages/tui/test/virtual-terminal.ts");
const { initTheme } = await load("packages/coding-agent/src/modes/interactive/theme/theme.ts");
